for f, m, date, s, a0, a1, hook, taf, rname, rtag, tags, kw, fc, rshort in B:
    n = Q[(s, a0)][0]
    ay = " ".join(f"{Q[(s, a)][1]} ({a})" for a in range(a0, a1 + 1))
    rng = f"{a0}" if a0 == a1 else f"{a0}-{a1}"
